public sealed class VersionTests
{
    [Theory]
    [InlineData("v2.3.0", "2.3.0")]
    [InlineData("version-6.7.6", "6.7.6")]
    [InlineData("0.60.8-alpine", "0.60.8")]
    [InlineData("2.0.3 (latest@2026-09-08)", "2.0.3")]
    [InlineData("18-vectorchord1.1.1-pgvector0.8.5", "1.1.1")]
    [InlineData("v26.6.1.1-stable", "26.6.1.1")]
    public void Parses_the_first_dotted_number(string text, string expected) => Assert.Equal(expected, Versions.Text(Versions.Parse(text)!));

    [Theory]
    [InlineData("latest")]
    [InlineData("unknown¹")]
    [InlineData("ffde877 (source rev)")]
    [InlineData("9")]
    [InlineData(null)]
    public void Has_no_version_when_there_is_no_dotted_number(string? text) => Assert.Null(Versions.Parse(text));

    [Theory]
    [InlineData("2.3.0", "2.3.0", 0)]
    [InlineData("2.3.1", "2.3.0", 1)]
    [InlineData("2.10.0", "2.9.9", 1)]
    [InlineData("3.0", "2.99.9", 1)]
    [InlineData("2.3", "2.3.0", 0)]
    [InlineData("0.29.4", "0.30.0", -1)]
    public void Compares_numerically_segment_by_segment(string a, string b, int sign) =>
        Assert.Equal(sign, Math.Sign(Versions.Compare(Versions.Parse(a)!, Versions.Parse(b)!)));

    [Theory]
    [InlineData("v1.2.3-rc1", true)]
    [InlineData("v1.2.3-rc.2", true)]
    [InlineData("1.2.3-beta", true)]
    [InlineData("v1.2.3-alpha.4", true)]
    [InlineData("nightly-2026-10-01", true)]
    [InlineData("v1.2.3-preview", true)]
    [InlineData("v1.2.3", false)]
    [InlineData("v26.6.1.1-stable", false)]
    [InlineData("3.4.0-alpine", false)]
    [InlineData("release-1.2.3", false)]
    public void Spots_prereleases(string tag, bool pre) => Assert.Equal(pre, Versions.IsPrerelease(tag));
}

